function detectCategory(name, code) {
  const n = (name || '').trim();
  const c = String(code || '').trim();
  if (n.startsWith('جاكيت') || n.startsWith('فيست') || c.startsWith('771')) return 'جاكيت';
  if (n.startsWith('سويت شيرت') || n.startsWith('سويت سيرت') || c.startsWith('772')) return 'سويت شيرت';
  if (n.startsWith('قميص') || c.startsWith('774')) return 'قميص';
  if (n.startsWith('بنطلون') || c.startsWith('775')) return 'بنطلون';
  if (n.startsWith('بلوزة') || c.startsWith('776')) return 'بلوزة';
  if (n.startsWith('طقم') || c.startsWith('777')) return 'طقم';
  if (n.startsWith('بلوفر') || n.startsWith('بدى') || c.startsWith('778')) return 'بلوفر';
  if (n.startsWith('جيب') || c.startsWith('779')) return 'جيب';
  return 'أخرى';
}

function parseCSV() {
  const lines = csvData.trim().split('\n');
  const products = [];
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(',');
    const code = parts[0].trim();
    const price = parseFloat(parts[1]) || 0;
    const name = parts[2].trim();
    const multiplier = parseInt(parts[7]) || 1;
    const description = `${price}/${multiplier}`;
    const stock_quantity = parseInt(parts[5]) || 0;
    const category = detectCategory(name, code);

    products.push({
      code,
      name,
      description,
      price,
      stock_quantity,
      low_stock_threshold: 10,
      category,
    });
  }
  return products;
}

